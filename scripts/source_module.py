"""站源模块接入。

站源不再写在 native/core 里，而是编译期由独立的 Go 模块接入：

    python scripts/build_native.py --platform windows --sources ../guoapp-sources

本模块负责生成两个「不入库」的文件，让 go 命令能找到站源模块并让它注册进二进制：

    native/go.work                 工作区，列出本仓库与各站源模块
    native/bridge/sources_gen.go   空导入站源模块（带 sources 编译标签，App 用）
    native/server/sources_gen.go   同上，本地服务版是另一个 main 包，必须各有一份

不传 --sources 时两个文件都会被删除，构建出的是「不含站源」的版本，
站源相关调用会返回「该站源未编入当前版本」。
"""

import argparse
import os
from pathlib import Path

GO_WORK_NAME = 'go.work'
GENERATED_NAME = 'sources_gen.go'
GENERATED_HEADER = '// Code generated by scripts/build_native.py; DO NOT EDIT.\n'
BUILD_TAG = 'sources'


def add_source_argument(parser):
    """给各平台构建脚本统一加 --sources。"""
    parser.add_argument('--sources', action='append', default=[], metavar='PATH',
                        help='接入站源模块目录（可多次指定，如 ../guoapp-sources）；不传则构建不含外置站源的版本')


def forward_arguments(sources):
    """把 --sources 列表摊平成子脚本参数：['--sources', p1, '--sources', p2]。"""
    return [value for path in sources for value in ('--sources', path)]


def module_path(go_mod):
    """读出 go.mod 里的模块路径。"""
    for line in go_mod.read_text(encoding='utf-8').splitlines():
        line = line.strip()
        if line.startswith('module '):
            return line.split(None, 1)[1].strip()
    raise SystemExit('go.mod 缺少 module 行：' + str(go_mod))


def go_directive(go_mod):
    """读出 go.mod 的 go 指令，go.work 要跟它一致。"""
    for line in go_mod.read_text(encoding='utf-8').splitlines():
        line = line.strip()
        if line.startswith('go '):
            return line.split(None, 1)[1].strip()
    return '1.25.0'


def generated_files(native_dir):
    """两个 main 包各要一份空导入：App 走 bridge，本地服务版走 server。"""
    return [native_dir / 'bridge' / GENERATED_NAME, native_dir / 'server' / GENERATED_NAME]


def clean(native_dir):
    """删掉上次生成的文件，避免换站源后残留。"""
    for path in [native_dir / GO_WORK_NAME, *generated_files(native_dir)]:
        if path.exists():
            path.unlink()


def configure(native_dir, sources):
    """生成 go.work 与 sources_gen.go，返回需要追加的 go build 参数。"""
    native_dir = Path(native_dir).resolve()
    clean(native_dir)
    if not sources:
        return []

    modules, uses = [], ['\t.']
    for raw in sources:
        path = Path(raw).resolve()
        if not (path / 'go.mod').is_file():
            raise SystemExit('站源目录缺少 go.mod：' + str(path))
        modules.append(module_path(path / 'go.mod'))
        uses.append('\t' + Path(os.path.relpath(path, native_dir)).as_posix())

    go_mod = native_dir / 'go.mod'
    content = 'go ' + go_directive(go_mod) + '\n\nuse (\n' + '\n'.join(uses) + '\n)\n'
    (native_dir / GO_WORK_NAME).write_text(content, encoding='utf-8')

    imports = ''.join('\t_ "' + name + '"\n' for name in modules)
    generated = (GENERATED_HEADER + '//go:build ' + BUILD_TAG + '\n\npackage main\n\n'
                 'import (\n' + imports + ')\n')
    for path in generated_files(native_dir):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(generated, encoding='utf-8')
    return ['-tags=' + BUILD_TAG]
